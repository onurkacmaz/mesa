// Turns a checkout of warpdotdev/command-signatures into the schemas this app
// ships. Run by hand when the upstream set is worth refreshing; the output is
// committed, so a normal build never touches the network.
//
//   node scripts/import-command-signatures.mjs <path-to-checkout>
//
// The trimming — and the argument for it — lives in src/commandSignature.mjs,
// which is where the tests are. This file only walks a directory.

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

import { trimSignature } from '../src/commandSignature.mjs';

const source = process.argv[2];
if (!source) {
  console.error('usage: node scripts/import-command-signatures.mjs <path-to-command-signatures-checkout>');
  process.exit(1);
}

const from = path.join(source, 'command-signatures', 'json');
const to = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'electron', 'command-schemas');

if (!fs.existsSync(from)) {
  console.error(`no command-signatures/json under ${source}`);
  process.exit(1);
}

fs.rmSync(to, { recursive: true, force: true });
fs.mkdirSync(to, { recursive: true });

let written = 0;
let bytes = 0;
for (const file of fs.readdirSync(from)) {
  if (!file.endsWith('.json')) continue;
  let spec;
  try {
    spec = JSON.parse(fs.readFileSync(path.join(from, file), 'utf8'));
  } catch {
    continue; // a spec that does not parse is one we do without
  }
  const trimmed = trimSignature(spec);
  if (!trimmed) continue;
  // Named after the FILE, not after the name inside it. Three upstream specs
  // claim a name another file already owns — hub.json calls itself `git`,
  // because it wraps git — and writing by the declared name let the wrapper's
  // much thinner spec land on top of the real one. Measured: git lost its
  // branch completion entirely that way. The filename is what the command is
  // actually called.
  const command = path.basename(file, '.json');
  if (!/^[A-Za-z0-9._-]+$/.test(command)) continue;
  trimmed.name = command;
  const text = JSON.stringify(trimmed);
  fs.writeFileSync(path.join(to, `${command}.json`), text);
  written += 1;
  bytes += text.length;
}

// The upstream licence travels with the data it covers.
fs.copyFileSync(path.join(source, 'LICENSE.md'), path.join(to, 'LICENSE.md'));
fs.writeFileSync(
  path.join(to, 'README.md'),
  [
    '# Command schemas',
    '',
    'Generated by `scripts/import-command-signatures.mjs` from',
    '[warpdotdev/command-signatures](https://github.com/warpdotdev/command-signatures) (MIT,',
    'see LICENSE.md here). Do not edit by hand — re-run the script instead.',
    '',
    'Each file describes one command: its subcommands, its flags, and the name of',
    'a generator for arguments that have to be looked up live. Every executable',
    'field in the upstream format (`generators`, `script`, `postProcess`,',
    '`generateSpec`, `loadSpec`) is dropped during the import, so nothing here is',
    'ever evaluated — a schema can name a generator this app already implements,',
    'and can do nothing else.',
    ''
  ].join('\n')
);

console.log(`wrote ${written} schemas, ${(bytes / 1024 / 1024).toFixed(2)}MB, to ${to}`);
