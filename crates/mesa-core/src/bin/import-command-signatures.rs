//! Turns a checkout of warpdotdev/command-signatures into the schemas this
//! app ships. Run by hand when the upstream set is worth refreshing; the
//! output is committed, so a normal build never touches the network.
//!
//!   cargo run -p mesa-core --bin import-command-signatures -- <checkout>
//!
//! The trimming — and the argument for it — lives in `command_signature`.

use std::{fs, path::PathBuf};

fn main() {
    let Some(source) = std::env::args().nth(1).map(PathBuf::from) else {
        eprintln!("usage: import-command-signatures <path-to-command-signatures-checkout>");
        std::process::exit(1);
    };
    let from = source.join("command-signatures").join("json");
    let to = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../mesa/assets/command-schemas");
    if !from.exists() {
        eprintln!("no command-signatures/json under {}", source.display());
        std::process::exit(1);
    }
    let _ = fs::remove_dir_all(&to);
    fs::create_dir_all(&to).expect("create schema dir");

    let (mut written, mut bytes) = (0, 0);
    for entry in fs::read_dir(&from).expect("read source").flatten() {
        let path = entry.path();
        if path.extension().and_then(|e| e.to_str()) != Some("json") {
            continue;
        }
        let Ok(text) = fs::read_to_string(&path) else { continue };
        let Ok(spec) = serde_json::from_str(&text) else { continue };
        let Some(mut trimmed) = mesa_core::command_signature::trim_signature(&spec, 3) else { continue };
        // Named after the FILE, not after the name inside it: hub.json calls
        // itself `git`, because it wraps git, and writing by the declared
        // name let the wrapper's thinner spec land on top of the real one.
        let command = path.file_stem().unwrap().to_string_lossy().to_string();
        if !command.chars().all(|c| c.is_ascii_alphanumeric() || "._-".contains(c)) {
            continue;
        }
        trimmed["name"] = serde_json::Value::String(command.clone());
        let out = serde_json::to_string(&trimmed).unwrap();
        bytes += out.len();
        fs::write(to.join(format!("{command}.json")), out).expect("write schema");
        written += 1;
    }
    // The upstream licence travels with the data it covers.
    let _ = fs::copy(source.join("LICENSE.md"), to.join("LICENSE.md"));
    let _ = fs::write(to.join("README.md"), README);
    println!("wrote {written} schemas, {:.2}MB, to {}", bytes as f64 / 1048576.0, to.display());
}

const README: &str = "# Command schemas

Generated by `cargo run -p mesa-core --bin import-command-signatures` from
[warpdotdev/command-signatures](https://github.com/warpdotdev/command-signatures) (MIT,
see LICENSE.md here). Do not edit by hand — re-run the importer instead.

Each file describes one command: its subcommands, its flags, and the name of
a generator for arguments that have to be looked up live. Every executable
field in the upstream format (`generators`, `script`, `postProcess`,
`generateSpec`, `loadSpec`) is dropped during the import, so nothing here is
ever evaluated — a schema can name a generator this app already implements,
and can do nothing else.
";
